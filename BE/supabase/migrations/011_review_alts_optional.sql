-- 011 후기 사진 설명을 선택으로 — 운영자는 승인만 누른다 (2026-10-26 사용자 결정)
--
-- 010 은 "사진 있는 글은 장마다 설명을 적어야 게시된다" 로 묶었다. 사용자
-- 결정으로 운영자 작업을 없앤다: 승인 버튼 하나로 게시된다.
--
-- 설명이 없는 사진은 화면이 자동 문구("작성자가 올린 사진 1/3")를 대체
-- 텍스트로 쓴다(`lib/review-images.ts` 의 reviewImageAlt). `alt=""` 로
-- 떨어뜨리지 않는다 — 그건 "정보 없는 장식" 이라는 거짓 선언이 된다(CLAUDE.md).
-- 운영자가 원하면 승인 화면에서 설명을 적을 수 있고, 적으면 그게 우선한다.
--
-- 짝 길이 제약(`reviews_image_alts_paired`)은 그대로 둔다 — 적는다면 장수와
-- 맞아야 한다. 빈 문자열 원소는 "그 장은 자동 문구" 라는 뜻이다.
-- ---------------------------------------------------------------------

alter table reviews drop constraint if exists reviews_image_alts_before_publish;

comment on column reviews.image_alts is
  'image_paths 와 1:1 대체 텍스트(선택). 비었거나 빈 문자열이면 화면이 자동 문구를 쓴다 — 011 주석 참고';
