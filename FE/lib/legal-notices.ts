/** 고지 한 줄 */
export interface LegalNoticeItem {
  text: string;
  /**
   * 운영자가 실제 계약 조건으로 채워야 하는 항목.
   * 문장 자체는 지금도 사실이지만(= "상담 시 안내"), 확정 정보가 들어오면 교체 대상이다.
   */
  pending?: boolean;
}

export interface LegalNoticeBlock {
  /** `<details>` 그룹 식별자 — DOM id 와 아코디언 name 에 쓴다 */
  id: string;
  title: string;
  /** 접힌 상태에서도 보이는 한 줄 요약 */
  summary: string;
  items: LegalNoticeItem[];
  /**
   * 요금표가 있을 때만 의미 있는 블록.
   * 요금 미등록 통신사 페이지에서는 렌더하지 않는다 (빈 맥락의 고지는 혼란만 준다).
   */
  requiresPrices?: boolean;
  /** 기본으로 펼쳐둘 블록 — 요금 표시 기준은 접어두면 고지 역할을 못 한다 */
  defaultOpen?: boolean;
}

