/** 아직 확정되지 않은 자리표시자인가. `TODO` 로 시작하거나 비어 있으면 참 */
export function isPlaceholder(v: string | null | undefined): boolean {
  return !v || v.trim() === "" || v.trim().startsWith("TODO");
}

